import { z } from 'zod';
import { chatMessageSchema } from './chat.js';
import { instantSchema } from './common.js';

/** The visitor's side: leave a message. Email or phone (at least one). */
export const enquiryBodySchema = z
  .object({
    token: z.string().min(1).max(2000),
    name: z.string().trim().min(1, 'Enter your name').max(100),
    email: z.union([z.literal(''), z.string().trim().toLowerCase().pipe(z.email('Enter a valid email').max(254))]),
    phone: z.union([z.literal(''), z.string().trim().regex(/^[+()\d\s-]{7,20}$/, 'Enter a valid phone number')]),
    need: z.string().trim().min(1, 'Tell us what you need').max(2000),
    consent: z.literal(true, { error: 'Please tick the box so we can reply' }),
  })
  .refine((b) => b.email || b.phone, { message: 'Give an email address or a phone number', path: ['email'] });
export type EnquiryBody = z.infer<typeof enquiryBodySchema>;

/** Shown next to the enquiry and booking forms; stored with each enquiry. */
export const consentText = (business: string) =>
  `I agree to ${business} storing these details to reply to me. They won't be used for anything else.`;

export const enquirySchema = z.object({
  id: z.uuid(),
  conversationId: z.uuid().nullable(),
  name: z.string(),
  email: z.string().nullable(),
  phone: z.string().nullable(),
  need: z.string(),
  createdAt: instantSchema,
});
export type Enquiry = z.infer<typeof enquirySchema>;

/** Booking through Slotwise, as the widget sees it. */
export const bookingServiceSchema = z.object({
  id: z.uuid(),
  name: z.string(),
  durationMin: z.number().int(),
  pricePence: z.number().int(),
});
export type BookingService = z.infer<typeof bookingServiceSchema>;
export const bookingServicesSchema = z.object({ items: z.array(bookingServiceSchema) });

export const slotsQuerySchema = z.object({
  token: z.string().min(1).max(2000),
  serviceId: z.uuid(),
  from: z.iso.date(),
  to: z.iso.date(),
});
export const slotSchema = z.object({ startsAt: z.iso.datetime(), localTime: z.string() });
export const slotsSchema = z.object({
  days: z.array(z.object({ date: z.iso.date(), slots: z.array(slotSchema) })),
});
export type Slots = z.infer<typeof slotsSchema>;

export const bookBodySchema = z.object({
  token: z.string().min(1).max(2000),
  serviceId: z.uuid(),
  startsAt: z.iso.datetime(),
  /** Generated by the widget per booking attempt, so a retry can't book twice. */
  idempotencyKey: z.uuid(),
  name: z.string().trim().min(1, 'Enter your name').max(100),
  email: z.string().trim().toLowerCase().pipe(z.email('Enter a valid email').max(254)),
  phone: z.union([z.literal(''), z.string().trim().regex(/^[+()\d\s-]{7,20}$/, 'Enter a valid phone number')]),
  consent: z.literal(true, { error: 'Please tick the box to book' }),
});
export type BookBody = z.infer<typeof bookBodySchema>;
export const bookResultSchema = z.object({ startsAt: z.iso.datetime(), serviceName: z.string() });

export const visitorTokenBodySchema = z.object({ token: z.string().min(1).max(2000) });

/** The staff side. */
export const conversationModeSchema = z.enum(['ai', 'human', 'closed']);
export const conversationSummarySchema = z.object({
  id: z.uuid(),
  mode: conversationModeSchema,
  assignedUserId: z.uuid().nullable(),
  assignedName: z.string().nullable(),
  handoverRequested: z.boolean(),
  lastMessage: z.string().nullable(),
  lastMessageAt: instantSchema,
  messageCount: z.number().int(),
});
export type ConversationSummary = z.infer<typeof conversationSummarySchema>;
export const conversationListSchema = z.object({ items: z.array(conversationSummarySchema), nextCursor: z.string().nullable() });
export type ConversationList = z.infer<typeof conversationListSchema>;
export const conversationDetailSchema = conversationSummarySchema.extend({ messages: z.array(chatMessageSchema) });
export type ConversationDetail = z.infer<typeof conversationDetailSchema>;
export const conversationParamsSchema = z.object({ workspaceId: z.uuid(), conversationId: z.uuid() });
export const staffReplyBodySchema = z.object({ text: z.string().trim().min(1).max(2000) });

/** Socket events from the server to staff dashboards. */
export interface StaffServerEvents {
  conversation: (c: ConversationSummary) => void;
  message: (e: { conversationId: string; message: z.infer<typeof chatMessageSchema> }) => void;
  'handover:requested': (c: ConversationSummary) => void;
}
